# Generates the "grant all technology" cheat event (id 9996) from techs.csv (produced by techscan.ps1)
# and replaces the existing 9996 block in PoliticalEvents.txt.
#
# A "tech = N" effect only completes ONE level per execution, so each tech is granted max_level times.
# Every step is wrapped in the mod's own idiom  OMG = { any_country = { limit = { tag = THIS ... } } }
# with a NOT = { tech = max } check, which is re-evaluated before each step -> stops exactly at the cap.
$r = Import-Csv (Join-Path $PSScriptRoot 'data\techs.csv')

# techs without max_level: use the highest level seen in a 1940 save / the history files (default 1)
$seen = @{}; Import-Csv (Join-Path $PSScriptRoot 'data\seen.csv') | ForEach-Object { $seen[$_.Name] = [int]$_.Seen }
$histMax = @{ fleet_auxiliary_submarine_doctrine = 4; small_bomb = 3; large_bomb = 3; mountain_infantry = 2; census_tabulation_machine = 2 }

# Never-researchable techs are skipped, except closed_hangar (the player's choice; the mod's steel event grants it the same way)
$includeNever = @('closed_hangar', 'proximity_fuze_ships')

# Exclusive choices that were NOT picked, plus nation-specific techs
$excludeNames = @(
    # engine / tank armour / vehicle type / ship steel / hangar
    'diesel_engine_design', 'cast_armour', 'casemate_vehicles', 'Cemented_armor', 'Vickers_steel', 'open_hangar',
    # light-air-only techs (heavy air picked)
    'light_weight_construction', 'heavy_planes_construction',
    # floatplane: torpedo picked
    'floatplane_dev_fighter', 'floatplane_dev_scout',
    # command style: Befehlstaktik picked
    'Auftragstaktik',
    # turret layout: three_four (3x4) picked, without its reverse variant
    'three_three', 'three_three_reverse', 'four_two', 'four_two_reverse', 'four_three', 'four_three_reverse',
    'five_two', 'five_two_reverse', 'three_four_reverse',
    # nation-specific
    'mustang_tech', 'Garand_tech', 'T_34_tech', 'sherman_tech', 'ppsh_pps_tech', 'katyusha_tech', 'mosquito_tech',
    'RP_3_tech', 'crocodile_tech', 'assault_rifles', 'tiger_tech', 'long_lance_tech', 'charb1_tech', 'alpini_tech',
    'nimrod_tech', 'Fletcher_class_tech', 'Independence_class_tech', 'QF17pdr_tech', 'SAS_tech', 'motobomba_tech',
    'CHC_light_units_tech', 'Luftwaffe_Infantry', 'banzai', 'main_battle_tank_technical_concept',
    # strategic doctrine starters other than Superior Firepower
    'blitzkrieg', 'grand_battle_plan', 'deep_battle_doctrine'
)

# Other doctrine trees and the division-size decreases are dropped; generic techs that live in those folders are kept
$excludeFolders = @('blitzkrieg_folder', 'deep_battle_folder', 'grand_battle_plan_folder', 'division_decrease_folder')
$keepInExcludedFolders = @('ww1_warfare', 'artillery_barrage', 'cavalry_pursuit_tactics', 'sniper_tactics',
    'political_indoctrination', 'political_integration', 'Befehlstaktik')

$kept = New-Object System.Collections.Generic.List[object]
foreach ($t in $r) {
    $n = $t.Name
    if ($t.Cat -eq 'NEVER' -and $includeNever -notcontains $n) { continue }
    if ($excludeNames -contains $n) { continue }
    if ($n -match '^(ss_|SS_|guard_|Guards_|NKVD_)') { continue }
    if ($excludeFolders -contains $t.Folder -and $keepInExcludedFolders -notcontains $n) { continue }
    $max = 1
    if ($t.Max) { $max = [int]$t.Max }
    else {
        if ($histMax.ContainsKey($n)) { $max = [Math]::Max($max, $histMax[$n]) }
        if ($seen.ContainsKey($n)) { $max = [Math]::Max($max, $seen[$n]) }
    }
    $kept.Add([pscustomobject]@{ Name = $n; Folder = $t.Folder; Max = $max })
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('')
[void]$sb.AppendLine('# Cheat: grant all technology (BlackICE 15.1). Console: event 9996')
[void]$sb.AppendLine('# One firing takes every listed tech to its max_level and never past it (safe to fire again).')
[void]$sb.AppendLine('# Choices: heavy air, gasoline engine, welded armour, special treatment steel, closed hangar,')
[void]$sb.AppendLine('#          superior firepower, turreted vehicles, torpedo floatplane, Befehlstaktik, 3+4 turrets, max division size')
[void]$sb.AppendLine('# Skipped: never-researchable, hidden trackers, nation-specific, SS and Guards techs.')
[void]$sb.AppendLine('# Generated by hoi3tmp/gen_event.ps1')
[void]$sb.AppendLine('country_event = {')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('	id = 9996')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('	is_triggered_only = yes')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('	title = "Grant all technology"')
[void]$sb.AppendLine('	desc = "Cheats"')
[void]$sb.AppendLine('	picture = "equipment_choice"')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('	option = {')
[void]$sb.AppendLine('		name = "Give us everything"')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('		# lock in the choices so the mod''s choice events do not ask again or switch them')
foreach ($f in 'heavy_air', 'heavy_air_gas_weld', 'gasoline_engine', 'welded_armour', 'special_treatment_steel',
    'superior_firepower', 'turret_choice', 'casemante_turret_choice', 'proximity_fuze_ships_set') {
    [void]$sb.AppendLine("		set_country_flag = $f")
}
foreach ($f in 'light_air', 'diesel_engine', 'cast_armour', 'cemented_armor', 'vickers_steel',
    'blitzkrieg', 'grand_battle_plan', 'deep_battle_doctrine', 'doctrine_delay', 'flag_tacs', 'Ordinamento_Pariani_Limitation') {
    [void]$sb.AppendLine("		clr_country_flag = $f")
}
[void]$sb.AppendLine('')
[void]$sb.AppendLine('		# each line = +1 level, skipped once the tech is at its max')
[void]$sb.AppendLine('		OMG = {')

$steps = 0
$kept | Group-Object Folder | Sort-Object Name | ForEach-Object {
    [void]$sb.AppendLine("			# $($_.Name)")
    foreach ($t in $_.Group) {
        for ($k = 1; $k -le $t.Max; $k++) {
            [void]$sb.AppendLine("			any_country = { limit = { tag = THIS NOT = { $($t.Name) = $($t.Max) } } $($t.Name) = 9999 }")
            $steps++
        }
    }
}
[void]$sb.AppendLine('		}')
[void]$sb.AppendLine('	}')
[void]$sb.AppendLine('	option = {')
[void]$sb.AppendLine('		name = "Not now"')
[void]$sb.AppendLine('	}')
[void]$sb.AppendLine('}')

$enc = [Text.Encoding]::GetEncoding(28591)
$ev = $sb.ToString() -replace '(?<!\r)\n', "`r`n"
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'mod\events\event_9996.txt'), $ev, $enc)

# replace the existing 9996 block (it is the last thing in the file) in PoliticalEvents.txt
$pf = 'C:\Users\jack\games\Hearts of Iron 3\tfh\mod\BlackICE 15.1\events\PoliticalEvents.txt'
$t = [IO.File]::ReadAllText($pf, $enc)
$start = $t.IndexOf("# Cheat: grant all technology")
if ($start -lt 0) { throw 'existing event 9996 header not found' }
$t = $t.Substring(0, $start).TrimEnd() + "`r`n" + $ev
[IO.File]::WriteAllText($pf, $t, $enc)

"techs: $($kept.Count)  level steps: $steps"
'braces open/close: ' + ([regex]::Matches($t, '\{').Count) + '/' + ([regex]::Matches($t, '\}').Count)
'event 9996 count: ' + ([regex]::Matches($t, 'id = 9996').Count)
